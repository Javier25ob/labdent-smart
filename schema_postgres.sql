-- SECCIÓN 1 - BASE DE DATOS (PostgreSQL / Supabase)
-- Mismo modelo que schema.sql (SQLite). Es idempotente: se puede ejecutar varias veces
-- sin borrar nada (CREATE ... IF NOT EXISTS).

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    rol TEXT NOT NULL,           -- Administrador, Técnico, Recepción
    usuario TEXT UNIQUE,         -- usuario de acceso al panel (NULL = sin acceso)
    clave_hash TEXT
);

CREATE TABLE IF NOT EXISTS odontologos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    telefono TEXT,
    clinica TEXT,
    usuario TEXT UNIQUE,         -- usuario de acceso al portal de cliente (NULL = sin acceso)
    clave_hash TEXT
);

CREATE TABLE IF NOT EXISTS pacientes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    odontologo_id INTEGER REFERENCES odontologos(id)
);

CREATE TABLE IF NOT EXISTS servicios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    precio DOUBLE PRECISION NOT NULL DEFAULT 0,       -- pesos colombianos (COP)
    dias_estimados INTEGER NOT NULL DEFAULT 5
);

CREATE TABLE IF NOT EXISTS materiales (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    unidad TEXT NOT NULL DEFAULT 'und',
    stock DOUBLE PRECISION NOT NULL DEFAULT 0,
    stock_minimo DOUBLE PRECISION NOT NULL DEFAULT 0,
    costo_unitario DOUBLE PRECISION NOT NULL DEFAULT 0  -- pesos colombianos (COP)
);

-- "Receta" de cada servicio: qué materiales y cuánto consume
CREATE TABLE IF NOT EXISTS servicio_materiales (
    servicio_id INTEGER NOT NULL REFERENCES servicios(id),
    material_id INTEGER NOT NULL REFERENCES materiales(id),
    cantidad DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (servicio_id, material_id)
);

CREATE TABLE IF NOT EXISTS ordenes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    odontologo_id INTEGER NOT NULL REFERENCES odontologos(id),
    paciente_id INTEGER NOT NULL REFERENCES pacientes(id),
    servicio_id INTEGER NOT NULL REFERENCES servicios(id),
    estado TEXT NOT NULL DEFAULT 'Recibida',
    fecha_ingreso TEXT NOT NULL,
    fecha_entrega_estimada TEXT NOT NULL,
    fecha_entrega_real TEXT,
    observaciones TEXT,
    consumo_registrado INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS historial_estados (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id INTEGER NOT NULL REFERENCES ordenes(id),
    estado TEXT NOT NULL,
    fecha TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS movimientos_inventario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id INTEGER NOT NULL REFERENCES materiales(id),
    tipo TEXT NOT NULL,          -- ENTRADA o SALIDA
    cantidad DOUBLE PRECISION NOT NULL,
    fecha TEXT NOT NULL,
    orden_id INTEGER REFERENCES ordenes(id),
    nota TEXT
);

-- Ajustes del laboratorio (nombre, WhatsApp, URL pública)
CREATE TABLE IF NOT EXISTS configuracion (
    clave TEXT PRIMARY KEY,
    valor TEXT NOT NULL DEFAULT ''
);

-- Índices sobre las columnas que más se consultan
CREATE INDEX IF NOT EXISTS idx_pacientes_odontologo ON pacientes(odontologo_id);
CREATE INDEX IF NOT EXISTS idx_ordenes_odontologo ON ordenes(odontologo_id);
CREATE INDEX IF NOT EXISTS idx_ordenes_estado ON ordenes(estado);
CREATE INDEX IF NOT EXISTS idx_historial_orden ON historial_estados(orden_id);
CREATE INDEX IF NOT EXISTS idx_movimientos_material_fecha ON movimientos_inventario(material_id, fecha);

-- SEGURIDAD (importante en Supabase): Supabase publica por defecto las tablas del esquema
-- "public" mediante su API REST. Con RLS activado y SIN políticas, esa API no puede leer ni
-- escribir nada. La aplicación no la usa: se conecta directo a PostgreSQL con el rol "postgres",
-- que se salta RLS, así que sigue funcionando igual.
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE odontologos ENABLE ROW LEVEL SECURITY;
ALTER TABLE pacientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE servicios ENABLE ROW LEVEL SECURITY;
ALTER TABLE materiales ENABLE ROW LEVEL SECURITY;
ALTER TABLE servicio_materiales ENABLE ROW LEVEL SECURITY;
ALTER TABLE ordenes ENABLE ROW LEVEL SECURITY;
ALTER TABLE historial_estados ENABLE ROW LEVEL SECURITY;
ALTER TABLE movimientos_inventario ENABLE ROW LEVEL SECURITY;
ALTER TABLE configuracion ENABLE ROW LEVEL SECURITY;
